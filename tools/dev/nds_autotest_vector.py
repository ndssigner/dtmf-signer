#!/usr/bin/env python3
"""Writes the DS emulator test's vector header (development only).

Usage: python3 tools/dev/nds_autotest_vector.py HOST_BINARY OUT_HEADER

The test (ports/nds/arm9/autotest.c, `make AUTOTEST=1`) plays what the
site's simulator of the screen firmware plays (site/config.json,
PROFILE-CABLE-QR's "simulator", mainnet): the seed of its keys vector,
with the simulator's PIN, then its PSBT vector. The signed
PSBT it must give is the host port's (`dtmf-signer-host sign`, HOST_BINARY):
its length and SHA-256 go in the header, with the seed's entropy, the PIN,
the PSBT and the fingerprints the screens must show. Test vectors only.
"""

import base64
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "third_party" / "ur-tones" / "reference" / "python"))

import ur_tones  # noqa: E402

PROFILE = "PROFILE-CABLE-QR"


def c_bytes(name, data):
    items = ["0x%02x," % b for b in data]
    lines = ["    " + "".join(items[k:k + 16]) for k in range(0, len(items), 16)]
    return "static const uint8_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))


def find(path, name):
    for v in json.loads((ROOT / path).read_text())["vectors"]:
        if v["name"] == name:
            return v
    sys.exit("%s: no vector %r" % (path, name))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    host, out = sys.argv[1], Path(sys.argv[2])

    # the screen firmware's simulator (the DS shows a screen too)
    profiles = json.loads((ROOT / "site" / "config.json").read_text())["profiles"]
    sim = next((p["simulator"] for p in profiles if p.get("id") == PROFILE), None)
    if sim is None:
        sys.exit("site/config.json: no simulator in %s" % PROFILE)
    pin = sim["pin"]
    net = sim["networks"]["mainnet"]
    pv = find("vectors/psbt-v0.json", net["psbt_vector"])
    kv = find("vectors/keys-v0.json", net["keys_vector"])
    if pv["entropy"] != kv["entropy"] or pv["passphrase"] or kv["passphrase"] \
            or pv["testnet"] or kv["testnet"] or pv["expect"] != "sign":
        sys.exit("the simulator's vectors do not match: one mainnet seed, no passphrase")
    entropy = bytes.fromhex(kv["entropy"])
    psbt = base64.b64decode(pv["psbt"])

    with tempfile.TemporaryDirectory() as tmp:
        f = Path(tmp) / "in.psbt"
        f.write_bytes(psbt)
        p = subprocess.run([host, "sign", "--ur", ur_tones.seed_to_ur(entropy), "--psbt", str(f)],
                           input="yes\n", capture_output=True, text=True, timeout=120)
    if p.returncode != 0:
        sys.exit("host sign failed (%d): %s" % (p.returncode, p.stderr))
    signed = base64.b64decode(p.stdout.strip().splitlines()[-1], validate=True)

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join([
        "/* Generated by tools/dev/nds_autotest_vector.py: the DS emulator test's",
        " * vector (site/config.json's simulator, mainnet). Test data only. */",
        "#ifndef AUTOTEST_VECTOR_H",
        "#define AUTOTEST_VECTOR_H",
        "",
        "#include <stdint.h>",
        "",
        "#define AUTOTEST_PSBT_VECTOR %s" % json.dumps(pv["name"]),
        "#define AUTOTEST_PIN %s" % json.dumps(pin),
        "#define AUTOTEST_SEED_FP %s" % json.dumps(kv["seed_fingerprint"]),
        "#define AUTOTEST_WALLET_FP %s" % json.dumps(kv["wallet_fingerprint"]),
        "/* the host port's signed PSBT (dtmf-signer-host sign) */",
        "#define AUTOTEST_SIGNED_LEN %du" % len(signed),
        "#define AUTOTEST_SIGNED_SHA256 \"%s\"" % hashlib.sha256(signed).hexdigest(),
        "",
        c_bytes("autotest_entropy", entropy),
        c_bytes("autotest_psbt", psbt),
        "#endif",
        "",
    ]))
    print("%s: %s, signed %d bytes, SHA-256 %s" % (out.name, pv["name"], len(signed),
                                                   hashlib.sha256(signed).hexdigest()))


if __name__ == "__main__":
    main()
