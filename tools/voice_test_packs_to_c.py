#!/usr/bin/env python3
"""Writes the voice packs the C pack test reads into a header.

Usage: python3 tools/voice_test_packs_to_c.py app/voice/packs/es.bin OUTPUT_H

The build runs this (a CMake custom command) and keeps the header in the
build directory. It holds:
- the committed Spanish pack and the first 4 bytes of its SHA-256 (the
  fingerprint the firmware computes on its own, checked against Python's);
- a Japanese pack that is data only: silent clips, numbered locally, with a
  grammar that groups by 10 000, to show a new language needs no new code.
"""

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools" / "voice"))
import make_pack  # noqa: E402

# Clip numbers of the Japanese test pack; 1..9 are the small numbers.
JA = {"juu": 10, "hyaku": 11, "sen": 12, "man": 13, "oku": 14, "sanbyaku": 15,
      "roppyaku": 16, "happyaku": 17, "sanzen": 18, "hassen": 19}


def ja_pack(count: int) -> bytes:
    small = [make_pack.NONE] * 100
    for n in range(1, 10):
        small[n] = n
    scales = [(10 ** 8, JA["oku"], make_pack.NONE, True),
              (10 ** 4, JA["man"], make_pack.NONE, True),
              (1000, JA["sen"], make_pack.NONE, False),
              (100, JA["hyaku"], make_pack.NONE, False),
              (10, JA["juu"], make_pack.NONE, False)]
    irr = []
    for value, name in ((300, "sanbyaku"), (600, "roppyaku"), (800, "happyaku"),
                        (3000, "sanzen"), (8000, "hassen")):
        irr += [(value, JA[name], 1), (value, JA[name], 2)]
    grammar = make_pack.encode_grammar({"small": small, "scales": scales, "irregulars": irr})
    clips = [[0] * 16 if 1 <= i < 20 else [] for i in range(count)]
    return make_pack.build_pack("ja", clips, grammar)


def array(name, data):
    rows = "\n".join("    " + "".join("0x%02x," % b for b in data[i:i + 24])
                     for i in range(0, len(data), 24))
    return "static const uint8_t %s[] = {\n%s\n};\n" % (name, rows)


def render(es: bytes, count: int) -> str:
    fp = hashlib.sha256(es).digest()[:4]
    out = [
        "/* Generated by tools/voice_test_packs_to_c.py. */",
        "#ifndef VOICE_TEST_PACKS_H",
        "#define VOICE_TEST_PACKS_H",
        "",
        "#include <stdint.h>",
        "",
        array("es_bin", es),
        "#define ES_BIN_LEN %du" % len(es),
        "static const uint8_t es_bin_fp[4] = {%s};" % ", ".join("0x%02x" % b for b in fp),
        "",
    ]
    out += ["#define JA_%s %d" % (k.upper(), v) for k, v in JA.items()]
    ja = ja_pack(count)
    out += ["", array("ja_pack", ja), "#define JA_PACK_LEN %du" % len(ja), "", "#endif", ""]
    return "\n".join(out)


def main(argv):
    if len(argv) != 3:
        raise SystemExit("usage: voice_test_packs_to_c.py ES_BIN OUTPUT_H")
    count = len(make_pack.load_phrases())
    Path(argv[2]).write_text(render(Path(argv[1]).read_bytes(), count))


if __name__ == "__main__":
    main(sys.argv)
