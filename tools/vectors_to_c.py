#!/usr/bin/env python3
"""Converts vectors/psbt-v0.json into a C header for the C tests.

Usage: python3 tools/vectors_to_c.py vectors/psbt-v0.json build/.../psbt_vectors.h

The build runs this (a CMake custom command) and keeps the header in the build
directory. Each vector becomes a psbt_vector: the PSBT and the entropy as byte
arrays, the expected error as its DS_ERR_* name (the test includes ds_core.h),
and for "sign" vectors the fee, the fee warning, the expected outputs and
which inputs are ours (those with an expected signature) with each expected
signature: the compressed public key and DER + sighash byte, as hex.
"""

import base64
import json
import sys
from pathlib import Path

KINDS = {"external": "DS_OUT_EXTERNAL", "change": "DS_OUT_CHANGE", "own": "DS_OUT_OWN"}


def c_string(s):
    out = '"'
    for ch in s.encode():
        if ch in (0x22, 0x5C):
            out += "\\" + chr(ch)
        elif 0x20 <= ch < 0x7F:
            out += chr(ch)
        else:
            out += "\\%03o" % ch
    return out + '"'


def c_bytes(name, data):
    items = ["0x%02x," % b for b in data] or ["0"]
    lines = ["    " + "".join(items[k:k + 16]) for k in range(0, len(items), 16)]
    return "static const uint8_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))


def render(data):
    out = [
        "/* Generated by tools/vectors_to_c.py from vectors/psbt-v0.json. */",
        "#ifndef PSBT_VECTORS_H",
        "#define PSBT_VECTORS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint64_t amount;",
        "    const char *address;    /* NULL when the script has no address */",
        "    const char *script_hex; /* NULL when it has one */",
        "    int kind;               /* DS_OUT_* */",
        "} psbt_vector_out;",
        "",
        "typedef struct {",
        "    const char *pubkey_hex; /* NULL: the input is not ours */",
        "    const char *sig_hex;    /* DER signature and the sighash byte */",
        "} psbt_vector_sig;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const uint8_t *entropy;",
        "    size_t entropy_len;",
        "    const char *passphrase;",
        "    int testnet;",
        "    const uint8_t *psbt;",
        "    size_t psbt_len;",
        "    int sign;      /* 1: expect \"sign\"; 0: expect \"reject\" */",
        "    int32_t error; /* reject: the expected error */",
        "    uint64_t fee;",
        "    int fee_warning;",
        "    const psbt_vector_out *outputs;",
        "    size_t n_outputs;",
        "    const char *inputs_ours; /* sign: one '1' (ours) or '0' per input */",
        "    const psbt_vector_sig *signatures; /* sign: one per input */",
        "} psbt_vector;",
        "",
    ]
    rows = []
    for n, v in enumerate(data["vectors"]):
        out.append(c_bytes("psbt_vector_entropy_%d" % n, bytes.fromhex(v["entropy"])))
        out.append(c_bytes("psbt_vector_psbt_%d" % n, base64.b64decode(v["psbt"])))
        sign = v["expect"] == "sign"
        outs = "NULL"
        n_out = 0
        ours = "NULL"
        sigs = "NULL"
        if sign:
            items = []
            for o in v["outputs"]:
                addr = c_string(o["address"]) if "address" in o else "NULL"
                spk = c_string(o["script_hex"]) if "script_hex" in o else "NULL"
                items.append("    {%dull, %s, %s, %s}," % (o["amount"], addr, spk, KINDS[o["kind"]]))
            out.append("static const psbt_vector_out psbt_vector_outputs_%d[] = {\n%s\n};\n"
                       % (n, "\n".join(items)))
            outs = "psbt_vector_outputs_%d" % n
            n_out = len(items)
            ours = c_string("".join("0" if x is None else "1" for x in v["signatures"]))
            items = ["    {NULL, NULL}," if x is None else
                     "    {%s, %s}," % (c_string(x["pubkey"]), c_string(x["sig"]))
                     for x in v["signatures"]]
            out.append("static const psbt_vector_sig psbt_vector_sigs_%d[] = {\n%s\n};\n"
                       % (n, "\n".join(items)))
            sigs = "psbt_vector_sigs_%d" % n
        rows.append(
            "    {%s, psbt_vector_entropy_%d, sizeof psbt_vector_entropy_%d, %s, %d,\n"
            "     psbt_vector_psbt_%d, sizeof psbt_vector_psbt_%d, %d, %s, %dull, %d, %s, %d, %s,\n"
            "     %s},"
            % (c_string(v["name"]), n, n, c_string(v["passphrase"]), 1 if v["testnet"] else 0,
               n, n, 1 if sign else 0, v["error"] if not sign else "DS_OK",
               v.get("fee", 0), 1 if v.get("fee_warning") else 0, outs, n_out, ours, sigs))
    out.append("static const psbt_vector psbt_vectors[] = {")
    out.extend(rows)
    out.append("};")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) != 3:
        raise SystemExit("usage: vectors_to_c.py VECTORS_JSON OUTPUT_H")
    data = json.loads(Path(argv[1]).read_text())
    Path(argv[2]).write_text(render(data))


if __name__ == "__main__":
    main(sys.argv)
