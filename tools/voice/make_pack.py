#!/usr/bin/env python3
"""Builds the spoken-prompt packs of the telephone build.

    python3 tools/voice/make_pack.py --lang es --out-c app/voice/pack_es.c
    python3 tools/voice/make_pack.py --header app/voice/ds_prompts.h
    python3 tools/voice/make_pack.py --adpcm-vector vectors/adpcm-v0.json

Per phrase: Piper (a subprocess) renders a WAV, which is resampled to 8 kHz,
trimmed of silence (below -45 dBFS, 30 ms of padding kept), normalised to a
-3 dBFS peak and encoded as IMA ADPCM. The pack layout (little-endian):

    "DSV1" | lang (2 ASCII) | u16 count
    count x { u32 offset, u32 bytes, i16 pred, u8 index, u8 pad }
    data

`offset` counts from the start of the pack. Clips are IMA ADPCM, low nibble
first, 8000 Hz; `pred` and `index` are the decoder state at the clip's start.
An empty phrase has `bytes` 0.

The building and parsing of packs is pure Python; rendering needs the
tools/voice/requirements.txt packages (see README.md).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import struct
import subprocess
import sys
import tempfile
import urllib.request
import wave
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import adpcm  # noqa: E402

HERE = Path(__file__).resolve().parent
RATE = 8000
THRESHOLD_DBFS = -45.0
PAD_MS = 30
PEAK_DBFS = -3.0
ENTRY = struct.Struct("<IIhBB")


# -- Pack ---------------------------------------------------------------

def build_pack(lang: str, clips) -> bytes:
    """clips: one int16 sample list per phrase, in phrases.json order."""
    assert len(lang) == 2 and lang.isascii()
    head = len(clips) * ENTRY.size + 8
    table, data = bytearray(), bytearray()
    for pcm in clips:
        pcm = list(pcm)
        if pcm:
            pred, index = pcm[0], 0
            blob = adpcm.encode(pcm, pred, index)
        else:
            pred, index, blob = 0, 0, b""
        table += ENTRY.pack(head + len(data), len(blob), pred, index, 0)
        data += blob
    return b"DSV1" + lang.encode("ascii") + struct.pack("<H", len(clips)) + bytes(table) + bytes(data)


def parse_pack(pack: bytes) -> list[dict]:
    if pack[:4] != b"DSV1":
        raise ValueError("not a DSV1 pack")
    (count,) = struct.unpack_from("<H", pack, 6)
    entries = []
    for i in range(count):
        offset, nbytes, pred, index, pad = ENTRY.unpack_from(pack, 8 + i * ENTRY.size)
        entries.append({"offset": offset, "bytes": nbytes, "pred": pred, "index": index, "pad": pad})
    return entries


# -- Phrases and generated C --------------------------------------------

def load_phrases() -> dict:
    return json.loads((HERE / "phrases.json").read_text(encoding="utf-8"))


def header_text(phrases: dict) -> str:
    lines = [
        "/* Generated by tools/voice/make_pack.py from tools/voice/phrases.json. */",
        "#ifndef DS_PROMPTS_H",
        "#define DS_PROMPTS_H",
        "",
        "#include <stdint.h>",
        "",
        "/* One prompt per entry, in the order of the packs. */",
        "enum ds_prompt {",
    ]
    lines += ["    DS_P_%s," % k.upper() for k in phrases]
    lines += [
        "    DS_P_COUNT",
        "};",
        "",
        "/* Voice packs: \"DSV1\" format, see tools/voice/make_pack.py. */",
        "extern const uint8_t ds_pack_es[];",
        "extern const uint32_t ds_pack_es_len;",
        "extern const uint8_t ds_pack_en[];",
        "extern const uint32_t ds_pack_en_len;",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def pack_c_text(lang: str, pack: bytes, voice_name: str) -> str:
    rows = []
    for i in range(0, len(pack), 20):
        rows.append("    " + ", ".join("0x%02x" % b for b in pack[i:i + 20]) + ",")
    return (
        "/* Generated by tools/voice/make_pack.py (do not edit).\n"
        " * Voice: %s (Piper), prompts from tools/voice/phrases.json;\n"
        " * licences in app/voice/VOICES.md. IMA ADPCM, 8000 Hz. */\n"
        "#include \"ds_prompts.h\"\n\n"
        "const uint8_t ds_pack_%s[] = {\n%s\n};\n\n"
        "const uint32_t ds_pack_%s_len = %d;\n"
    ) % (voice_name, lang, "\n".join(rows), lang, len(pack))


# -- Voices and rendering (the part that needs the venv) -----------------

def cache_dir() -> Path:
    return Path(os.environ.get("DTMF_VOICE_CACHE", Path.home() / ".cache" / "dtmf-signer" / "voices"))


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch_voice(lang: str) -> tuple[Path, dict]:
    voice = json.loads((HERE / "voices.json").read_text())["voices"][lang]
    cache = cache_dir()
    cache.mkdir(parents=True, exist_ok=True)
    for name, info in voice["files"].items():
        path = cache / name
        if not path.exists():
            print("downloading", name, file=sys.stderr)
            urllib.request.urlretrieve(info["url"], path)
        if sha256(path) != info["sha256"]:
            raise SystemExit("SHA-256 mismatch for %s; delete it from the cache" % path)
    return cache / (voice["name"] + ".onnx"), voice


def piper_wav(model: Path, text: str, out: Path) -> None:
    subprocess.run(
        [sys.executable, "-m", "piper", "-m", str(model), "-f", str(out),
         "--noise-scale", "0", "--noise-w-scale", "0"],
        input=text.encode("utf-8"), check=True, capture_output=True,
    )


def read_wav(path: Path):
    import numpy as np
    with wave.open(str(path), "rb") as w:
        assert w.getsampwidth() == 2 and w.getnchannels() == 1
        rate = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float64) / 32768.0
    return x, rate


def resample(x, rate_in: int, rate_out: int = RATE):
    """Windowed-sinc (Kaiser) resampler, low-passed below the new Nyquist."""
    import numpy as np
    if len(x) == 0:
        return x
    ratio = rate_in / rate_out
    cutoff = 0.45 * rate_out / rate_in          # fraction of the input rate
    half = int(np.ceil(8 / (2 * cutoff)))       # about 8 sinc lobes each side
    n_out = int(len(x) / ratio)
    pos = np.arange(n_out) * ratio
    base = np.floor(pos).astype(np.int64)
    taps = np.arange(-half + 1, half + 1)
    idx = base[:, None] + taps[None, :]
    t = idx - pos[:, None]
    win = np.i0(8.0 * np.sqrt(np.clip(1 - (t / half) ** 2, 0, 1))) / np.i0(8.0)
    h = 2 * cutoff * np.sinc(2 * cutoff * t) * win
    xp = np.concatenate([np.zeros(half), x, np.zeros(half + 1)])
    return (xp[np.clip(idx + half, 0, len(xp) - 1)] * h).sum(axis=1)


def condition(x):
    """Trim below -45 dBFS keeping 30 ms either side, peak to -3 dBFS."""
    import numpy as np
    keep = np.nonzero(np.abs(x) >= 10 ** (THRESHOLD_DBFS / 20))[0]
    if len(keep) == 0:
        return []
    pad = RATE * PAD_MS // 1000
    y = np.concatenate([np.zeros(pad), x[keep[0]:keep[-1] + 1], np.zeros(pad)])
    y = y * (10 ** (PEAK_DBFS / 20) / np.abs(y).max())
    return [int(v) for v in np.clip(np.round(y * 32767), -32768, 32767)]


def render_clips(lang: str, phrases: dict):
    model, voice = fetch_voice(lang)
    clips = []
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "p.wav"
        for key, text in ((k, v[lang]) for k, v in phrases.items()):
            if not text:
                clips.append([])
                continue
            piper_wav(model, text, wav)
            x, rate = read_wav(wav)
            clips.append(condition(resample(x, rate)))
    return clips, voice["name"]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--lang", choices=["es", "en"])
    ap.add_argument("--out-c", help="write the pack as a C file (with --lang)")
    ap.add_argument("--out-bin", help="write the raw pack (with --lang)")
    ap.add_argument("--header", help="write ds_prompts.h")
    ap.add_argument("--adpcm-vector", help="write vectors/adpcm-v0.json")
    a = ap.parse_args()
    phrases = load_phrases()
    if a.header:
        Path(a.header).write_text(header_text(phrases), encoding="utf-8")
    if a.adpcm_vector:
        Path(a.adpcm_vector).write_text(json.dumps(adpcm.sample_vector(), indent=1) + "\n")
    if a.out_c or a.out_bin:
        if not a.lang:
            ap.error("--out-c/--out-bin need --lang")
        clips, name = render_clips(a.lang, phrases)
        pack = build_pack(a.lang, clips)
        secs = sum(len(c) for c in clips) / RATE
        print("%s: %d bytes, %.1f s of speech, %d phrases" % (a.lang, len(pack), secs, len(clips)))
        if a.out_c:
            Path(a.out_c).write_text(pack_c_text(a.lang, pack, name), encoding="utf-8")
        if a.out_bin:
            Path(a.out_bin).write_bytes(pack)
    return 0


if __name__ == "__main__":
    sys.exit(main())
