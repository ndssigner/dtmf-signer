#!/usr/bin/env python3
"""Converts vectors/adpcm-v0.json into a C header for the voice test.

Usage: python3 tools/adpcm_vector_to_c.py vectors/adpcm-v0.json build/.../adpcm_vector.h

The build runs this (a CMake custom command) and keeps the header in the
build directory: the ADPCM bytes, the start state and the expected samples.
"""

import json
import sys
from pathlib import Path


def lines(items):
    return "\n".join("    " + " ".join(items[k:k + 12]) for k in range(0, len(items), 12))


def render(v):
    data = bytes.fromhex(v["adpcm_hex"])
    return "\n".join([
        "/* Generated by tools/adpcm_vector_to_c.py from vectors/adpcm-v0.json. */",
        "#ifndef ADPCM_VECTOR_H",
        "#define ADPCM_VECTOR_H",
        "",
        "#include <stdint.h>",
        "",
        "#define ADPCM_VECTOR_PRED %d" % v["pred"],
        "#define ADPCM_VECTOR_INDEX %d" % v["index"],
        "",
        "static const uint8_t adpcm_vector_bytes[] = {",
        lines(["0x%02x," % b for b in data]),
        "};",
        "",
        "static const int16_t adpcm_vector_decoded[] = {",
        lines(["%d," % s for s in v["decoded"]]),
        "};",
        "",
        "#endif",
        "",
    ])


def main(argv):
    if len(argv) != 3:
        raise SystemExit("usage: adpcm_vector_to_c.py VECTOR_JSON OUTPUT_H")
    Path(argv[2]).write_text(render(json.loads(Path(argv[1]).read_text())))


if __name__ == "__main__":
    main(sys.argv)
