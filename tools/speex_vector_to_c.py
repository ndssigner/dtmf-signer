#!/usr/bin/env python3
"""Converts vectors/speex-v0.json into a C header for the Speex checks.

Usage: python3 tools/speex_vector_to_c.py vectors/speex-v0.json OUTPUT_H

The build runs this (a CMake custom command, for the host test and for the
simulator's wasm) and keeps the header in the build directory: the frames,
concatenated, where each starts, and the SHA-256 of the decoded PCM.
"""

import json
import sys
from pathlib import Path


def lines(items):
    return "\n".join("    " + " ".join(items[k:k + 12]) for k in range(0, len(items), 12))


def render(v):
    frames = [bytes.fromhex(h) for h in v["frames"]]
    if not frames or any(not 1 <= len(f) <= 62 for f in frames):
        raise SystemExit("speex vector: each frame must be 1..62 bytes")
    sha = v["pcm_sha256"].lower()
    if len(bytes.fromhex(sha)) != 32:
        raise SystemExit("speex vector: pcm_sha256 must be 32 bytes")
    offsets = [0]
    for f in frames:
        offsets.append(offsets[-1] + len(f))
    data = b"".join(frames)
    return "\n".join([
        "/* Generated by tools/speex_vector_to_c.py from vectors/speex-v0.json. */",
        "#ifndef SPEEX_VECTOR_H",
        "#define SPEEX_VECTOR_H",
        "",
        "#include <stdint.h>",
        "",
        "#define SPEEX_VECTOR_QUALITY %d" % v["quality"],
        "#define SPEEX_VECTOR_FRAMES %du" % len(frames),
        '#define SPEEX_VECTOR_PCM_SHA256 "%s"' % sha,
        "",
        "/* Frame f is speex_vector_bytes[offsets[f] .. offsets[f + 1]). */",
        "static const uint16_t speex_vector_offsets[] = {",
        lines(["%d," % o for o in offsets]),
        "};",
        "",
        "static const uint8_t speex_vector_bytes[] = {",
        lines(["0x%02x," % b for b in data]),
        "};",
        "",
        "#endif",
        "",
    ])


def main(argv):
    if len(argv) != 3:
        raise SystemExit("usage: speex_vector_to_c.py VECTOR_JSON OUTPUT_H")
    Path(argv[2]).write_text(render(json.loads(Path(argv[1]).read_text())))


if __name__ == "__main__":
    main(sys.argv)
